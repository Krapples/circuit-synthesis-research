"""Write native/src/conditional_cost3.hpp from the conditional three-input cost table.

Usage: python conditional_singleton_header.py TABLE.bin OUT.hpp

For each complement-normalized three-input target f (row min(f, 255 ^ f)), bit i of the mask is set when the
one-gate function ONE[i] is incompatible with a minimum circuit of f: M(f, {ONE[i]}) = L(f) + 1. The table
entries for singletons are exact (L <= M <= L + 1), so only these bits are exported.
"""
import sys
from pathlib import Path

ONE = (3, 5, 10, 12, 17, 34, 48, 63, 68, 80, 95, 119)


def main():
    table = Path(sys.argv[1]).read_bytes()
    assert len(table) == 128 * 4096
    masks, costs = [], []
    for f in range(128):
        base = table[f * 4096]
        bits = 0
        for i in range(12):
            v = table[f * 4096 + (1 << i)]
            assert v in (base, base + 1), (f, i, base, v)
            bits |= (v > base) << i
        masks.append(bits)
        costs.append(base)
    rows = ',\n    '.join(', '.join(f'0x{m:03x}' for m in masks[i:i + 8]) for i in range(0, 128, 8))
    crow = ',\n    '.join(', '.join(str(c) for c in costs[i:i + 16]) for i in range(0, 128, 16))
    out = f"""// Generated by sat-search/experiments/conditional_singleton_header.py from the conditional cost table
// (results/restriction_certificates/conditional_cost3.bin). Do not edit.
//
// Three-input columns: bit r is the value on row r, variable t is bit t of r. Index: min(f, 255 ^ f).
// kOneGate3[i]: the twelve one-gate functions modulo complement.
// kIncompatible3[f] bit i: M(f, {{kOneGate3[i]}}) = L(f) + 1, i.e. no minimum free-NOT AIG of f contains a gate
// computing kOneGate3[i]. kCost3Normalized[f] = L(f).
#pragma once
#include <array>
#include <cstdint>

namespace conditional_cost3 {{
inline constexpr std::array<uint8_t, 12> kOneGate3{{{', '.join(map(str, ONE))}}};
inline constexpr std::array<uint16_t, 128> kIncompatible3{{
    {rows}}};
inline constexpr std::array<uint8_t, 128> kCost3Normalized{{
    {crow}}};
}}  // namespace conditional_cost3
"""
    Path(sys.argv[2]).write_text(out)
    print('targets', 128, 'incompatible pairs', sum(bin(m).count('1') for m in masks))


if __name__ == '__main__':
    main()
