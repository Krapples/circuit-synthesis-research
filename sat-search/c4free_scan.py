"""Accounting-lemma scan (NOTES_L1343.md): on C4-free graphs, does every monotone circuit for the edge function
need at least the star cost s = |E| + tau - 1 gates?

For every connected C4-free graph with nmin..nmax vertices (generated by vertex addition, isomorphs removed):
 1. the monotone ordered-terminal bound (formula + output + Sperner/chain/separation ports) is tried first;
    if it reaches s, the graph is settled analytically;
 2. otherwise monotone exact-size searches at s - 1 and s - 2 (exact G covers G - 2, G - 4, ...) run over all
    first-gate pieces. A WITNESS refutes the lemma (the circuit is printed and verified); UNSAT everywhere
    confirms it for that graph.
Records go to results/c4free_scan.jsonl (one line per graph); graphs already recorded are skipped.
Usage: python c4free_scan.py [nmin] [nmax] [workers]"""
import os, sys, json, time, itertools
from multiprocessing import Pool
import warnings
import networkx as nx
warnings.filterwarnings("ignore", category=UserWarning)
import cube_search as cs

from rulesets import fast_flags  # canonical --fast rule set (verify/test_rulesets.py)
FAST = fast_flags(monotone=True)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results', 'c4free_scan.jsonl')


def has_c4_through(g, v):
    nb = list(g[v])
    for a, b in itertools.combinations(nb, 2):
        if len((set(g[a]) & set(g[b])) - {v}) > 0:
            return True
    return False


def c4free_graphs(nmax):
    """All C4-free graphs (connected or not) on 1..nmax vertices, by levels; isomorphs removed."""
    levels = {1: [nx.empty_graph(1)]}
    for n in range(2, nmax + 1):
        buckets = {}
        for g in levels[n - 1]:
            for k in range(n):
                for nb in itertools.combinations(range(n - 1), k):
                    h = g.copy()
                    h.add_node(n - 1)
                    h.add_edges_from((n - 1, u) for u in nb)
                    if has_c4_through(h, n - 1):
                        continue
                    key = nx.weisfeiler_lehman_graph_hash(h, iterations=3)
                    lst = buckets.setdefault(key, [])
                    if not any(nx.is_isomorphic(h, o) for o in lst):
                        lst.append(h)
        levels[n] = [g for lst in buckets.values() for g in lst]
    return levels


def tau(n, edges):
    for k in range(n + 1):
        for C in itertools.combinations(range(n), k):
            if all(u in C or v in C for u, v in edges):
                return k


def mono_bound(edges):
    T = cs._anti([(1 << u) | (1 << v) for u, v in edges])
    cs.ORDERED[0] = True
    costs = cs.port_costs(T, mono=True, separation=True, profile=True, formula=True, output=True)
    return cs.port_binary_lb(T, costs)


def piece(job):
    key, n, edges, G, cube = job
    masks = [(1 << u) | (1 << v) for u, v in edges]
    _, st, circ, dt, _ = cs.run_cube((n, masks, G, 'maplechrono', cube, True, True, dict(FAST)))
    ok = None
    if st == 'WITNESS':
        ok = all(cs.evaluate(n, circ, x) == any(x & m == m for m in masks) for x in range(1 << n))
    return key, G, cube, st, circ, ok, dt


if __name__ == '__main__':
    nmin = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    nmax = int(sys.argv[2]) if len(sys.argv) > 2 else 7
    workers = int(sys.argv[3]) if len(sys.argv) > 3 else 22
    t0 = time.time()
    done = set()
    if os.path.exists(OUT):
        for line in open(OUT, encoding='utf-8'):
            done.add(json.loads(line)['key'])
    levels = c4free_graphs(nmax)
    graphs = []
    for n in range(nmin, nmax + 1):
        for g in levels[n]:
            if g.number_of_edges() and nx.is_connected(g):
                edges = sorted(tuple(sorted(e)) for e in g.edges())
                graphs.append((n, edges))
    print(f'{len(graphs)} connected C4-free graphs with {nmin}..{nmax} vertices ({time.time() - t0:.0f}s); '
          f'{sum(1 for n, e in graphs if f"{n}:{e}" in done)} already recorded', flush=True)
    rec = open(OUT, 'a', encoding='utf-8')
    jobs, info = [], {}
    nanal = 0
    for n, edges in graphs:
        key = f'{n}:{edges}'
        if key in done:
            continue
        s = len(edges) + tau(n, edges) - 1
        b = mono_bound(edges)
        if b >= s:
            nanal += 1
            rec.write(json.dumps(dict(key=key, n=n, E=len(edges), star=s, bound=b, result='analytical')) + '\n')
            continue
        auts = cs.automorphisms(n, edges)
        cubes = [c for c in [(op, l, r) for op in (0, 1) for r in range(n) for l in range(r)] if cs.orbit_min(c, auts)]
        info[key] = dict(n=n, E=len(edges), star=s, bound=b, left=0, witness=None, t=0.0)
        for G in (s - 1, s - 2):
            if G >= n - 1:
                for c in cubes:
                    jobs.append((key, n, edges, G, c))
                    info[key]['left'] += 1
    rec.flush()
    print(f'{nanal} settled by the analytical bound; {len(info)} graphs need SAT ({len(jobs)} pieces)', flush=True)
    refuted = 0
    with Pool(workers) as p:
        for key, G, cube, st, circ, ok, dt in p.imap_unordered(piece, jobs):
            d = info[key]
            d['left'] -= 1; d['t'] += dt
            if st == 'WITNESS' and d['witness'] is None:
                d['witness'] = dict(G=G, circuit=circ, verified=ok)
                print(f'WITNESS (lemma fails): {key} star {d["star"]}, circuit with {G} gates, verified={ok}: {circ}',
                      flush=True)
                refuted += 1
            elif st == 'STOPPED':
                d['stopped'] = True
            if d['left'] == 0:
                res = 'refuted' if d['witness'] else 'stopped' if d.get('stopped') else 'sat-unsat'
                rec.write(json.dumps(dict(key=key, n=d['n'], E=d['E'], star=d['star'], bound=d['bound'], result=res,
                                          witness=d['witness'], seconds=round(d['t'], 1))) + '\n'); rec.flush()
    print(f'RESULT: {len(graphs)} graphs; {nanal} analytical, {len(info) - refuted} confirmed by SAT, '
          f'{refuted} counterexamples ({time.time() - t0:.0f}s)')
