"""Generate the Lean certificate for C(f16102) >= 8 in the free-NOT AIG model (2026-11-26).

This mirrors the checker in sat-search/lean/SatBridge/Meta16102Aig.lean on raw 6-input tables, with no
canonical forms. Each state stores the largest bound the checker accepts. Bit k of a table is the value at
the point whose input w is bit w of k.

Usage: python aig8_lean_cert.py [out.lean]
"""
import sys
from functools import lru_cache

BIG = 1000
PTS = range(64)


def bit(t, k):
    return (t >> k) & 1


def restrict(t, v, b):
    return sum(bit(t, (k & ~(1 << v)) | (b << v)) << k for k in PTS)


def is_lit(t):
    if t in (0, (1 << 64) - 1):
        return True
    for u in range(6):
        for neg in (0, 1):
            if all(bit(t, k) == ((k >> u) & 1) ^ neg for k in PTS):
                return True
    return False


def is_gate(t):
    for i in range(6):
        for j in range(6):
            if i == j:
                continue
            for ai in (0, 1):
                for aj in (0, 1):
                    for neg in (0, 1):
                        if all(bit(t, k) == ((((k >> i) & 1) ^ ai) & (((k >> j) & 1) ^ aj)) ^ neg
                               for k in PTS):
                            return True
    return False


def nonconst(t):
    return any(bit(t, k) != bit(t, 0) for k in PTS)


def upd(k, v, b):
    return (k & ~(1 << v)) | (b << v)


def factors(t, i, j, ai, aj):
    for k in PTS:
        a = bit(t, upd(upd(k, i, ai), j, aj))
        if a != bit(t, upd(upd(k, i, ai), j, 1 - aj)) or a != bit(t, upd(upd(k, i, 1 - ai), j, aj)):
            return False
    return True


@lru_cache(maxsize=None)
def lb(t):
    if is_lit(t):
        return 0
    if is_gate(t):
        return 1
    return min(1000, bound(t))


def fact(t, v, bv, cls):
    c = [lb(restrict(t, v, 0)), lb(restrict(t, v, 1))]
    o = 1 - bv
    if cls == 0:
        return max(2 + c[bv], 1 + c[o])
    base = max(2 + max(c), 3 + c[bv])
    if cls == 1:
        return max(base, (3 if nonconst(restrict(t, v, o)) else 2) + c[o])
    if cls == 2:
        return max(base, (4 if nonconst(restrict(t, v, bv)) else 3) + c[bv])
    return 3 + max(c)


def pair_bound(t, i, j, ai, aj):
    fac = factors(t, i, j, ai, aj)
    best = BIG
    for ci in range(4):
        for cj in range(4):
            if ci == 0 and cj == 0 and not fac:
                continue
            best = min(best, max(fact(t, i, ai, ci), fact(t, j, aj, cj)))
    return best


def bound(t):
    # A pair with an inessential input scores at least 1 + lb(t) in the checker, so it never attains the
    # minimum; skipping it avoids the self-reference.
    ess = [v for v in range(6) if restrict(t, v, 0) != restrict(t, v, 1)]
    return min(pair_bound(t, i, j, ai, aj) for i in ess for j in ess if i != j
               for ai in (0, 1) for aj in (0, 1))


def table_16102():
    bits = [0] * 19 + [1, 0] + [1] * 11 + [0, 0] + [1] * 14 + [0, 0] + [1] * 14
    return sum(b << k for k, b in enumerate(bits))


def main():
    sys.setrecursionlimit(10000)
    root = table_16102()
    print("LB(root) =", lb(root))
    entries = sorted((t, lb(t)) for t in states() if lb(t) > 0)
    stored = dict(entries)
    print("entries:", len(entries))
    if len(sys.argv) > 1:
        rows = []
        for t, v in entries:
            rs = [restrict(t, w, b) for w in range(6) for b in (0, 1)]
            cs = [stored.get(r, 0) for r in rs]
            ns = ["true" if nonconst(r) else "false" for r in rs]
            rows.append(f"  ⟨{t}, {v}, {rs}, {cs}, [{', '.join(ns)}]⟩")
        with open(sys.argv[1], "w", encoding="utf-8") as fh:
            fh.write(HEADER.format(root=root))
            fh.write(",\n".join(rows))
            fh.write("]\n\nend SatBridge.Meta16102Aig\n")


HEADER = """/-
Certificate data for `C(f16102) >= 8` in the free-NOT AIG model, generated by
`sat-search/results/mid_not_16102/aig8_lean_cert.py` (2026-11-26). Do not edit by hand.

Each entry is a 6-input truth table `tt` (bit `k` is the value at the point whose input `w` is bit `w`
of `k`), its claimed bound `lb`, its twelve restrictions `rs` (index `2v + b` for `x_v := b`), their
claimed bounds `cs`, and whether each is nonconstant. `Meta16102Aig.checkAll` verifies all of it.
-/
import Mathlib

namespace SatBridge.Meta16102Aig

structure E where
  tt : ℕ
  lb : ℕ
  rs : List ℕ
  cs : List ℕ
  ns : List Bool

/-- The posted table as a number. -/
def T16102 : ℕ := {root}

def entries : List E := [
"""


def states():
    seen, todo = set(), [table_16102()]
    while todo:
        t = todo.pop()
        if t in seen:
            continue
        seen.add(t)
        if is_lit(t) or is_gate(t):
            continue
        for v in range(6):
            for b in (0, 1):
                todo.append(restrict(t, v, b))
    return seen


if __name__ == "__main__":
    main()
